#!/usr/bin/env node
/**
 * Pulls the live start.ng catalogue into `src/lib/games.ts`.
 *
 *   node scripts/sync-startng.mjs
 *
 * Sources
 *   https://api.start.ng/games        every game + its cover, maker, plays
 *   https://api.start.ng/tags/<slug>  which games belong to a category
 *   https://start.ng/                 the human titles (the API only ships slugs)
 *
 * Categories are start.ng's own tags — nothing is invented here, they are just
 * curated down to the seven that read well as a place you can dive into.
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const API = "https://api.start.ng";
const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, "../src/lib/games.ts");

/** key → the tag slug it is built from. Order defines the category rail. */
const CATEGORIES = [
  { key: "runners", tag: "endless-runners", label: "Runners", blurb: "Dash, dodge, keep going", accent: "#d8fd71" },
  { key: "naija", tag: "nigerian-themed", label: "Naija", blurb: "Lagos, jollof, danfo", accent: "#f5a640" },
  { key: "catch", tag: "catch-and-dodge", label: "Catch", blurb: "Quick hands, easy to learn", accent: "#db2967" },
  { key: "brainy", tag: "brainy-games", label: "Brainy", blurb: "Think fast, think smart", accent: "#346fdf" },
  { key: "neon", tag: "neon-and-cyberpunk", label: "Neon", blurb: "Glow, drift, cyberpunk", accent: "#8e4fd6" },
  { key: "racing", tag: "racing-and-driving", label: "Racing", blurb: "Cars, bikes and danfo", accent: "#ff6b4a" },
  { key: "action", tag: "shooting-and-action", label: "Action", blurb: "Aim, fire and fight", accent: "#3ee0d0" },
];

const FALLBACK_COVER = "/cover-fallback.svg";

async function json(path) {
  const res = await fetch(`${API}${path}`, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(`${path} → ${res.status}`);
  return res.json();
}

async function text(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} → ${res.status}`);
  return res.text();
}

/** The A→Z list on the homepage carries the display titles. */
function titlesFrom(html) {
  const map = new Map();
  const re = /<li><a href="\/games\/([^"]+)">([^<]+)<\/a>\s*<span>by ([^<]+)<\/span>/g;
  for (const [, slug, title, by] of html.matchAll(re)) {
    map.set(slug, { title: title.trim(), by: by.trim() });
  }
  return map;
}

const games = await json("/games");
const shelves = await json("/discover/shelves");
const current = await json("/tournaments/current").catch(() => null);
const recent = await json("/tournaments/recent").catch(() => []);
const home = await text("https://start.ng/");
const titles = titlesFrom(home);

const tagLists = await Promise.all(
  CATEGORIES.map(async (c) => [c.key, (await json(`/tags/${c.tag}`)).games.map((g) => g.name)]),
);
const byCategory = Object.fromEntries(tagLists);

const list = games
  .filter((g) => !g.hidden)
  .map((g) => {
    const human = titles.get(g.name);
    const cats = CATEGORIES.filter((c) => byCategory[c.key].includes(g.name)).map((c) => c.key);
    return {
      slug: g.name,
      title: human?.title ?? g.name.replace(/-/g, " ").replace(/\b\w/, (m) => m.toUpperCase()),
      by: human?.by ?? g.by,
      cover: g.cover_url || FALLBACK_COVER,
      url: g.url,
      plays: g.plays ?? 0,
      tags: cats,
      description: g.description ?? "",
    };
  })
  .sort((a, b) => b.plays - a.plays || a.title.localeCompare(b.title));

const missing = list.filter((g) => g.cover === FALLBACK_COVER).map((g) => g.slug);
if (missing.length) console.log(`no cover → poster fallback: ${missing.join(", ")}`);

const source = `/* eslint-disable */
// AUTO-GENERATED by scripts/sync-startng.mjs — do not edit by hand.
// Source of truth: https://api.start.ng, refreshed ${new Date().toISOString().slice(0, 10)}.

export type CategoryKey = ${CATEGORIES.map((c) => JSON.stringify(c.key)).join(" | ")};

export type Game = {
  slug: string;
  title: string;
  by: string;
  cover: string;
  url: string;
  plays: number;
  /** categories this game appears under, in rail order */
  tags: CategoryKey[];
  description: string;
};

export type Category = {
  key: CategoryKey;
  label: string;
  blurb: string;
  /** the light this category paints the tunnel with */
  accent: string;
};

export const CATEGORIES: Category[] = ${JSON.stringify(CATEGORIES.map(({ key, label, blurb, accent }) => ({ key, label, blurb, accent })), null, 2)};

/** the homepage shelves, exactly as start.ng serves them */
export const SHELVES: {
  key: string;
  title: string;
  note: string;
  slugs: string[];
}[] = ${JSON.stringify([
    { key: "most_played", title: "Most played", note: "What everyone else is on right now" },
    { key: "new", title: "Fresh from the repos", note: "Just pushed, just approved" },
    { key: "most_improved", title: "Most improved", note: "Rewritten, republished, better" },
  ].map((s) => ({ ...s, slugs: (shelves[s.key] ?? []).slice(0, 10) })), null, 2)};

export type TournamentGame = {
  slug: string;
  title: string;
  by: string;
  cover: string;
  url: string;
  players: number;
  metric: string;
};

/** today's tournament, exactly as start.ng serves it */
export const TOURNAMENT: { endsAt: string; games: TournamentGame[] } = ${JSON.stringify({
    endsAt: current?.ends_at ?? "",
    games: (current?.games ?? []).slice(0, 5).map((g) => ({
      slug: g.name,
      title: titles.get(g.name)?.title ?? g.name,
      by: titles.get(g.name)?.by ?? "",
      cover: g.cover_url || FALLBACK_COVER,
      url: g.url,
      players: g.players ?? 0,
      metric: g.leaderboard?.[0]?.label ?? "Score",
    })),
  }, null, 2)};

/** recent tournaments, for the past-winners column */
export const RECENT_TOURNAMENTS: {
  id: number;
  winner: string | null;
  points: number | null;
  games: number;
}[] = ${JSON.stringify(
    recent.slice(0, 7).map((t) => ({
      id: t.id,
      winner: t.winner?.name ?? null,
      points: t.winner?.points ?? null,
      games: t.games.length,
    })),
    null,
  )};

export const GAMES: Game[] = ${JSON.stringify(list, null, 2)};

const BY_SLUG = new Map(GAMES.map((g) => [g.slug, g]));

export function gameFor(slug: string | null | undefined): Game | undefined {
  return slug ? BY_SLUG.get(slug) : undefined;
}

export function gamesIn(category: CategoryKey): Game[] {
  return GAMES.filter((g) => g.tags.includes(category));
}

export function categoryFor(category: CategoryKey): Category {
  return CATEGORIES.find((c) => c.key === category) ?? CATEGORIES[0];
}

export function titleOf(slug: string): string {
  return gameFor(slug)?.title ?? slug;
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, source, "utf8");
console.log(`wrote ${list.length} games across ${CATEGORIES.length} categories → src/lib/games.ts`);
